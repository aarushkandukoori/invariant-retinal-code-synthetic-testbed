'''Synthetic retinal-population simulator.

Reference implementation of a PROPOSAL. No experiments have been run and no
results are claimed. EVERYTHING produced here is SYNTHETIC / MOCK data drawn
from Gaussians; it is not a model of any real retina and uses no real neural,
animal or lab data.

Model (linear case):  r = A u_k + B g_j + eps,  eps ~ N(0, Sigma)
  u_k : scene codes (K x p),  g_j : nuisance features (J x q), shared by all scenes
  Sigma = s^2 (I + rho V V^T)  (low-rank plus diagonal noise correlations)
Optional nonlinearity: softplus on the mean response (Gaussian noise is still
added afterwards; Poisson-like noise is NOT implemented in this skeleton).
'''
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

SYNTHETIC_LABEL = (
    'SYNTHETIC / MOCK DATA - generated by src/simulator.py; '
    'not real neural recordings'
)


@dataclass(frozen=True)
class SimConfig:
    '''Simulator knobs (synthetic population only).'''

    n_cells: int = 40
    n_scenes: int = 8
    scene_dim: int = 3
    nuisance_dim: int = 2
    n_conditions: int = 6  # nuisance settings, shared across scenes
    n_trials: int = 20
    overlap: float = 0.0  # 0 = orthogonal scene/nuisance subspaces, 1 = aligned
    noise_scale: float = 1.0
    noise_corr: float = 0.5
    noise_rank: int = 3
    scene_strength: float = 2.0
    nuisance_strength: float = 2.0
    nonlinearity: str = 'none'  # 'none' or 'softplus'


@dataclass
class Population:
    '''A simulated population. `synthetic` is always True.'''

    responses: np.ndarray  # (M, N) trials x cells
    scene: np.ndarray  # (M,) int scene index
    cond: np.ndarray  # (M,) int nuisance-condition index
    nuis_feats: np.ndarray  # (J, q) nuisance features per condition
    scene_codes: np.ndarray  # (K, p)
    A: np.ndarray  # (N, p) planted scene loading
    B: np.ndarray  # (N, q) planted nuisance loading
    Sigma: np.ndarray  # (N, N) planted noise covariance
    linear: bool
    synthetic: bool = True
    label: str = SYNTHETIC_LABEL


def simulate(cfg: SimConfig, seed: int = 0) -> Population:
    '''Draw one SYNTHETIC population with planted ground truth.'''
    N, K, p, q = cfg.n_cells, cfg.n_scenes, cfg.scene_dim, cfg.nuisance_dim
    J, T = cfg.n_conditions, cfg.n_trials
    if not 0.0 <= cfg.overlap <= 1.0:
        raise ValueError('overlap must be in [0, 1]')
    if p + q > N:
        raise ValueError('need scene_dim + nuisance_dim <= n_cells')
    if cfg.nonlinearity not in ('none', 'softplus'):
        raise ValueError('nonlinearity must be none or softplus')
    rng = np.random.default_rng(seed)

    Q, _ = np.linalg.qr(rng.standard_normal((N, p + q)))
    A = Q[:, :p] * cfg.scene_strength
    B0 = Q[:, p:]
    A_aligned = Q[:, np.arange(q) % p]
    o = cfg.overlap
    B = (np.sqrt(1.0 - o) * B0 + np.sqrt(o) * A_aligned) * cfg.nuisance_strength

    U = rng.standard_normal((K, p))
    G = rng.standard_normal((J, q))  # independent of scene index
    V = rng.standard_normal((N, cfg.noise_rank)) / np.sqrt(N)
    s, rho = cfg.noise_scale, cfg.noise_corr
    Sigma = s**2 * (np.eye(N) + rho * V @ V.T)

    mean = (U @ A.T)[:, None, :] + (G @ B.T)[None, :, :]  # (K, J, N)
    if cfg.nonlinearity == 'softplus':
        mean = np.logaddexp(0.0, mean)
    z = rng.standard_normal((K, J, T, N))
    z2 = rng.standard_normal((K, J, T, cfg.noise_rank))
    eps = s * (z + np.sqrt(rho) * z2 @ V.T)
    X = (mean[:, :, None, :] + eps).reshape(-1, N)
    scene = np.repeat(np.arange(K), J * T)
    cond = np.tile(np.repeat(np.arange(J), T), K)
    return Population(X, scene, cond, G, U, A, B, Sigma,
                      linear=(cfg.nonlinearity == 'none'))


def planted_covariances(pop: Population) -> tuple[np.ndarray, np.ndarray]:
    '''Exact (S_B, S_N) of the mean response; linear case only.'''
    if not pop.linear:
        raise ValueError('planted covariances are exact only for the linear model')
    Uc = pop.scene_codes - pop.scene_codes.mean(axis=0)
    Gc = pop.nuis_feats - pop.nuis_feats.mean(axis=0)
    S_B = pop.A @ (Uc.T @ Uc / len(Uc)) @ pop.A.T
    S_N = pop.B @ (Gc.T @ Gc / len(Gc)) @ pop.B.T
    return S_B, S_N


def save_population(pop: Population, path: str | Path) -> None:
    '''Save a SYNTHETIC population (the file carries the synthetic label).'''
    np.savez_compressed(
        path, responses=pop.responses, scene=pop.scene, cond=pop.cond,
        nuis_feats=pop.nuis_feats, scene_codes=pop.scene_codes, A=pop.A,
        B=pop.B, Sigma=pop.Sigma, linear=np.array(pop.linear),
        synthetic=np.array(True), label=np.array(SYNTHETIC_LABEL),
    )


def load_synthetic_population(path: str | Path) -> Population:
    '''Load a population saved by save_population; refuses unlabeled files.'''
    d = np.load(path)
    if 'synthetic' not in d.files or not bool(d['synthetic']):
        raise ValueError('refusing to load a file not labeled synthetic')
    return Population(
        d['responses'], d['scene'], d['cond'], d['nuis_feats'],
        d['scene_codes'], d['A'], d['B'], d['Sigma'],
        linear=bool(d['linear']),
    )
